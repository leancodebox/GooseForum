import { readdir, rm } from 'node:fs/promises'
import { join, relative } from 'node:path'
import { runTypesGenerator } from 'i18next-cli'
import {
  fallbackLanguages, generatedDirectory, locales, readCatalog, requiresIcu, root,
  serverNamespace, sourceLocale, translationStatus, writeIfChanged,
} from './i18n-catalog.mjs'

const relativeOutput = relative(root, generatedDirectory)
export const toolkitConfig = {
  locales,
  extract: {
    input: ['apps/web/src/**/*.{ts,tsx}', 'packages/runtime/src/**/*.{ts,tsx}', 'packages/theme-default/src/**/*.{ts,tsx}'],
    output: relativeOutput + '/{{language}}/{{namespace}}.json',
    primaryLanguage: sourceLocale,
    defaultNS: 'site.auth',
    messageFormat: 'icu',
  },
  types: {
    input: [relativeOutput + '/zh/*.json'],
    output: 'packages/i18n/src/i18next.d.ts',
    resourcesFile: relativeOutput + '/resources.d.ts',
  },
}

const renderJson = value => JSON.stringify(value, null, 2) + '\n'
const generatedHeader = '// Generated by pnpm i18n:generate.\n'

function dictionary(namespace, entries, locale) {
  const resource = {}
  let icu = false
  for (const [key, entry] of Object.entries(entries)) {
    const value = locale === sourceLocale ? entry.source
      : translationStatus(entry, locale) === 'ready' ? entry.translations[locale].text
      : undefined
    if (value === undefined) continue
    icu ||= requiresIcu(value)
    const parts = namespace === serverNamespace ? [key] : key.split('.')
    const leaf = parts.pop()
    let group = resource
    for (const part of parts) group = (group[part] ??= {})
    group[leaf] = value
  }
  return { resource, icu }
}

function loaderModule(namespaces) {
  const ready = JSON.stringify(namespaces)
  const loaders = locales.flatMap(locale => namespaces.map(namespace => {
    const path = './' + locale + '/' + namespace + '.json'
    return '  ' + JSON.stringify(locale + '/' + namespace) + ': () => import(' + JSON.stringify(path) + '),'
  }))
  return generatedHeader + 'export const namespaces = ' + ready + ' as const\n' +
    'export const loaders = {\n' + loaders.join('\n') + '\n}\n'
}

export async function generate(catalog) {
  catalog ??= await readCatalog()
  const groups = { site: [], admin: [], shared: [] }
  const files = new Map()
  const needsFallback = {}
  const icuNamespaces = {}
  for (const [namespace, entries] of catalog) {
    groups[namespace.split('.')[0]].push(namespace)
    for (const locale of locales) {
      const { resource, icu } = dictionary(namespace, entries, locale)
      if (icu) (icuNamespaces[locale] ??= []).push(namespace)
      files.set(locale + '/' + namespace + '.json', renderJson(resource))
      if (locale !== sourceLocale && Object.values(entries).some(entry => translationStatus(entry, locale) !== 'ready'))
        (needsFallback[locale] ??= []).push(namespace)
    }
  }
  for (const [group, namespaces] of Object.entries(groups))
    files.set(group + '.ts', loaderModule(namespaces))
  files.set('fallback.ts', generatedHeader +
    "export const sourceLocale = '" + sourceLocale + "'\n" +
    'export const fallbackLanguages = ' + JSON.stringify(fallbackLanguages, null, 2) + ' as const\n' +
    'export const icuNamespaces: Record<string, readonly string[]> = ' + renderJson(icuNamespaces) +
    'export const needsFallback: Record<string, readonly string[]> = ' + renderJson(needsFallback))

  await Promise.all([...files].map(([path, data]) => writeIfChanged(join(generatedDirectory, path), data)))
  for (const locale of locales) {
    for (const file of await readdir(join(generatedDirectory, locale))) {
      const path = locale + '/' + file
      if (file.endsWith('.json') && !files.has(path)) await rm(join(generatedDirectory, path))
    }
  }
  await runTypesGenerator(toolkitConfig, { quiet: true })
}
