	req := AuthorizeRequest{ClientID: "client-1", RedirectURI: "https://app.example/callback", ResponseType: "code", Scope: []string{"openid", "offline_access"}, Prompt: []string{"consent"}, CodeChallenge: base64URLSHA256(verifier), CodeChallengeMethod: "S256"}
