func TestConcurrentRefreshReuseRevokesWinningFamily(t *testing.T) {
	p, store := testProvider(t)
	ctx := context.Background()
	verifier := "concurrent-refresh-token-verifier-43-characters-long"
	code, err := p.Authorize(ctx, AuthorizeRequest{ClientID: "client-1", RedirectURI: "https://app.example/callback", ResponseType: "code", Scope: []string{"openid", "offline_access"}, CodeChallenge: base64URLSHA256(verifier), CodeChallengeMethod: "S256", Prompt: []string{"consent"}}, testAuthentication(), true)
	if err != nil {
		t.Fatal(err)
	}
	issued, err := p.ExchangeCode(ctx, TokenRequest{GrantType: "authorization_code", Code: code.Code, ClientID: "client-1", ClientSecret: "secret", AuthMethod: ClientSecretPost, RedirectURI: "https://app.example/callback", CodeVerifier: verifier})
	if err != nil {
		t.Fatal(err)
	}
	request := TokenRequest{GrantType: "refresh_token", RefreshToken: issued.RefreshToken, ClientID: "client-1", ClientSecret: "secret", AuthMethod: ClientSecretPost}
	results := make(chan *TokenResponse, 2)
	var wg sync.WaitGroup
	for range 2 {
		wg.Add(1)
		go func() { defer wg.Done(); result, _ := p.Refresh(ctx, request); results <- result }()
	}
	wg.Wait()
	close(results)
	var winner *TokenResponse
	for result := range results {
		if result != nil {
			if winner != nil {
				t.Fatal("refresh token had multiple winners")
			}
			winner = result
		}
	}
	if winner == nil {
		t.Fatal("refresh token had no winner")
	}
	stored, _ := store.GetRefreshToken(ctx, hash(winner.RefreshToken))
	if stored == nil || stored.RevokedAt == nil {
		t.Fatal("reuse did not revoke the winning token family")
	}
	if _, err := p.ValidateAccessToken(ctx, winner.AccessToken); !errors.Is(err, ErrTokenRevoked) {
		t.Fatalf("reuse did not revoke family access token: %v", err)
	}
}

func base64URLSHA256(value string) string {
	sum := sha256.Sum256([]byte(value))
	return base64.RawURLEncoding.EncodeToString(sum[:])
}

