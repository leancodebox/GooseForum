func TestRefreshRotationAndRevocation(t *testing.T) {
	p, store := testProvider(t)
	ctx := context.Background()
	// Use the S256 challenge generated by the helper below.
	verifier := "a-test-verifier-with-at-least-forty-three-characters"
	challenge := base64URLSHA256(verifier)
	code, err := p.Authorize(ctx, AuthorizeRequest{ClientID: "client-1", RedirectURI: "https://app.example/callback", ResponseType: "code", Scope: []string{"openid", "email", "offline_access"}, Nonce: "nonce", CodeChallenge: challenge, CodeChallengeMethod: "S256", Prompt: []string{"consent"}}, testAuthentication(), true)
	if err != nil {
		t.Fatal(err)
	}
	tokens, err := p.ExchangeCode(ctx, TokenRequest{GrantType: "authorization_code", Code: code.Code, ClientID: "client-1", ClientSecret: "secret", AuthMethod: ClientSecretPost, RedirectURI: "https://app.example/callback", CodeVerifier: verifier})
	if err != nil || tokens.RefreshToken == "" || tokens.AccessToken == "" {
		t.Fatalf("exchange failed: %v", err)
	}
	next, err := p.Refresh(ctx, TokenRequest{GrantType: "refresh_token", RefreshToken: tokens.RefreshToken, ClientID: "client-1", ClientSecret: "secret", AuthMethod: ClientSecretPost})
	if err != nil || next.RefreshToken == tokens.RefreshToken {
		t.Fatalf("refresh rotation failed: %v", err)
	}
	claims, err := p.UserInfo(ctx, next.AccessToken)
	if err != nil || claims.Subject != "u-1" || claims.Email != "alice@example.com" || claims.Name != "" {
		t.Fatalf("unexpected scoped userinfo: %+v, %v", claims, err)
	}
	if _, err := p.Refresh(ctx, TokenRequest{GrantType: "refresh_token", RefreshToken: tokens.RefreshToken, ClientID: "client-1", ClientSecret: "secret", AuthMethod: ClientSecretPost}); err == nil {
		t.Fatal("expected rotated token to be rejected")
	}
	if _, err := p.Refresh(ctx, TokenRequest{GrantType: "refresh_token", RefreshToken: next.RefreshToken, ClientID: "client-1", ClientSecret: "secret", AuthMethod: ClientSecretPost}); err == nil {
		t.Fatal("expected refresh family to be revoked after token reuse")
	}
	if err := p.Revoke(ctx, TokenRevocationRequest{Token: next.RefreshToken, ClientID: "client-1", ClientSecret: "secret", AuthMethod: ClientSecretPost, TokenTypeHint: "refresh_token"}); err != nil {
		t.Fatal(err)
	}
	if token, _ := store.GetRefreshToken(ctx, hash(next.RefreshToken)); token.RevokedAt == nil {
		t.Fatal("expected refresh token to be revoked")
	}
	storedRefresh, _ := store.GetRefreshToken(ctx, hash(next.RefreshToken))
	if err := p.RevokeRefreshTokenFamily(ctx, storedRefresh.FamilyID); err != nil {
		t.Fatal(err)
	}
	if _, err := p.ValidateAccessToken(ctx, next.AccessToken); !errors.Is(err, ErrTokenRevoked) {
		t.Fatalf("family access token survived reuse: %v", err)
	}
}

